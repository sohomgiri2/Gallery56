fun parseHexColorOrNull(hex: String): Color? {
    val clean = hex.trim().removePrefix("#")
    return try {
        when (clean.length) {
            6 -> Color(("FF$clean").toLong(16))
            8 -> Color(clean.toLong(16))
            else -> null
        }
    } catch (_: Throwable) {
        null
    }
}

fun colorToHex(color: Color): String {
    val r = (color.red * 255).toInt().coerceIn(0, 255)
    val g = (color.green * 255).toInt().coerceIn(0, 255)
    val b = (color.blue * 255).toInt().coerceIn(0, 255)
    return String.format("#%02X%02X%02X", r, g, b)
}

/**
 * Guarantees readable foreground contrast on any arbitrary surface or container background.
 */
fun ensureReadableTextColor(
    candidate: Color,
    background: Color,
    isDarkSurface: Boolean,
): Color {
    val bgLum = background.luminance()
    val candLum = candidate.luminance()
    val brighter = maxOf(bgLum, candLum) + 0.05f
    val darker = minOf(bgLum, candLum) + 0.05f
    val ratio = brighter / darker
    return if (ratio >= 4.5f) {
        candidate
    } else {
        if (isDarkSurface || bgLum < 0.35f) Color(0xFFF4F7FB) else Color(0xFF0F172A)
    }
}

